// Bakes the globes for the 410x502 panel, error-diffused to RGB565 (no
// banding in the night skies):
// - src/data/backdrop.ts: Yule's globe window (everything that moves is
//   inside it) as base64 little-endian words, built in so the app runs
//   without a card;
// - public/art/base.png: the panel below the window (the wooden base, the
//   same in every globe), drawn once as an asset;
// - .gea/sd/yule/globes/<id>.565: every globe's window as raw little-endian
//   words, for the microSD card (scripts/push.sh copies them over);
// - src/data/globes.ts: the globes from art/globes/<id>.json, and their
//   light bulbs, found in each painting.
//
//   node scripts/bake.mjs

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");
const WIDTH = 410;
const HEIGHT = 502;
// Source pixels to panel pixels: the globe (centre 515,640 in the 1024x1536
// source) and the base fill the panel height.
const SCALE = 0.38;
const OFFSET_X = Math.round(WIDTH / 2 - 515 * SCALE);
const OFFSET_Y = Math.round(2 - 89 * SCALE);
// The live window on the panel: x, y, width, height.
const WINDOW = { x: 18, y: 0, width: 374, height: 378 };
// Darker than this is the black surround: true black on the AMOLED.
const BLACK_LEVEL = 10;
// The globes in menu order. Each one's life is in art/globes/<id>.json,
// all in source pixels of its 1024x1536 painting (see docs/HOW-IT-WORKS.md
// and scripts/overlay.mjs): solids, lights, glass, lamp, chimney, sway, and
// boxes its light bulbs are looked for in.
const ORDER = [
  "yule",
  "gingerbread",
  "nordic",
  "chapel",
  "aurora",
  "sleigh",
  "snowmen",
  "neon",
  "pixel",
  "lighthouse",
  "toytown",
  "tree-farm",
  "castle",
  "carousel",
  "polar-cub",
  "penguins",
  "santa-rocking",
  "cardinals",
  "bear-puppy",
  "ferris-wheel",
  "ice-stage",
  "roses",
  "cabin-classic",
  "viaduct",
  "camp",
  "woodland-tree",
  "santa-fishing",
];
const MAX_BULBS = 48;

const sdDir = join(APP, ".gea/sd/yule/globes");
mkdirSync(sdDir, { recursive: true });
const bulbs = [];
const bulbStarts = [];
const globes = [];
for (const id of ORDER) {
  const data = JSON.parse(readFileSync(join(APP, `art/globes/${id}.json`), "utf8"));
  const source = id === "yule" ? join(APP, "art/backdrop.png") : join(APP, `art/globes/${id}.jpg`);
  const { words, pixels, width } = await bake(source);
  const window = cutWindow(words);
  writeFileSync(join(sdDir, `${id}.565`), Buffer.from(window.buffer));

  bulbStarts.push(bulbs.length / 5);
  for (const box of data.bulbs) {
    const area = { left: box[0], top: box[1], right: box[2], bottom: box[3] };
    bulbs.push(...findBulbs(pixels, width, area, MAX_BULBS - bulbs.length / 5 + bulbStarts.at(-1)));
  }
  globes.push(globeLine(id, data));
  console.log(
    `${id}: ${bulbs.length / 5 - bulbStarts.at(-1)} bulbs, ${data.solids.length} solids, ${data.warm.length} warm`,
  );

  if (id === "yule") {
    writeYule(window);
    await writeBase(words);
  }
}
bulbStarts.push(bulbs.length / 5);

writeFileSync(
  join(APP, "src/data/globes.ts"),
  `// Generated by scripts/bake.mjs from art/globes/*.json. Do not edit.

// Light bulbs on the panel: x, y, r, g, b each; globe g's are
// BULB_STARTS[g] up to BULB_STARTS[g + 1].
export const BULBS = [${bulbs.join(", ")}];
export const BULB_STARTS = [${bulbStarts.join(", ")}];

// The globes in menu order, one per line (read by src/lib/globes.ts).
export const GLOBE_TEXT =
  "${globes.join("\\n")}";
`,
);

// A globe as one line of text, "id|name|style|numbers": fireplaces, lamp,
// windows, tree, then the solids (count, then per solid back, front,
// frontRow, lands, outline length, outline), then warm, glass, pool,
// chimney and sway, each as its length and its values. (src/lib/globes.ts
// reads it; text, as a large array literal is more than the compiler
// splits cleanly.)
function globeLine(id, data) {
  const values = [data.fireplaces, data.lamp, data.windows, data.tree, data.solids.length];
  for (const solid of data.solids) {
    values.push(solid.back, solid.front, solid.frontRow, solid.lands ? 1 : 0, solid.outline.length, ...solid.outline);
  }
  for (const field of [data.warm, data.glass, data.pool, data.chimney, data.sway]) {
    const flat = field.flat();
    values.push(flat.length, ...flat);
  }
  return `${id}|${data.name}|${data.style}|${values.join(",")}`;
}

// The source scaled and placed on the panel, error-diffused to RGB565 words;
// also the source's own pixels, for the light finders.
async function bake(source) {
  const meta = await sharp(source).metadata();
  const scaledW = Math.round(meta.width * SCALE);
  const scaledH = Math.round(meta.height * SCALE);
  const scaled = await sharp(source).resize(scaledW, scaledH, { kernel: "lanczos3" }).removeAlpha().raw().toBuffer();

  const rgb = new Float32Array(WIDTH * HEIGHT * 3);
  for (let y = 0; y < HEIGHT; y++) {
    const sy = y - OFFSET_Y;
    if (sy < 0 || sy >= scaledH) continue;

    for (let x = 0; x < WIDTH; x++) {
      const sx = x - OFFSET_X;
      if (sx < 0 || sx >= scaledW) continue;

      const from = (sy * scaledW + sx) * 3;
      const to = (y * WIDTH + x) * 3;
      rgb[to] = scaled[from];
      rgb[to + 1] = scaled[from + 1];
      rgb[to + 2] = scaled[from + 2];
    }
  }

  const pixels = await sharp(source).removeAlpha().raw().toBuffer();
  return { words: dither(rgb), pixels, width: meta.width };
}

// Floyd-Steinberg onto the RGB565 grid, serpentine.
function dither(rgb) {
  const words = new Uint16Array(WIDTH * HEIGHT);
  const levels = [31, 63, 31];
  const add = (x, y, c, value) => {
    if (x < 0 || x >= WIDTH || y >= HEIGHT) return;

    rgb[(y * WIDTH + x) * 3 + c] += value;
  };
  for (let y = 0; y < HEIGHT; y++) {
    const forward = (y & 1) === 0;
    const ahead = forward ? 1 : -1;
    for (let step = 0; step < WIDTH; step++) {
      const x = forward ? step : WIDTH - 1 - step;
      const at = (y * WIDTH + x) * 3;
      const black = rgb[at] + rgb[at + 1] + rgb[at + 2] < BLACK_LEVEL * 3;
      const q = [0, 0, 0];
      for (let c = 0; c < 3; c++) {
        const value = black ? 0 : Math.min(255, Math.max(0, rgb[at + c]));
        const level = Math.round((value / 255) * levels[c]);
        q[c] = level;
        const error = black ? 0 : value - (level * 255) / levels[c];
        add(x + ahead, y, c, (error * 7) / 16);
        add(x - ahead, y + 1, c, (error * 3) / 16);
        add(x, y + 1, c, (error * 5) / 16);
        add(x + ahead, y + 1, c, (error * 1) / 16);
      }
      words[y * WIDTH + x] = (q[0] << 11) | (q[1] << 5) | q[2];
    }
  }
  return words;
}

function cutWindow(words) {
  const window = new Uint16Array(WINDOW.width * WINDOW.height);
  for (let y = 0; y < WINDOW.height; y++) {
    const from = (WINDOW.y + y) * WIDTH + WINDOW.x;
    window.set(words.subarray(from, from + WINDOW.width), y * WINDOW.width);
  }
  return window;
}

function writeYule(window) {
  const base64 = Buffer.from(window.buffer).toString("base64");
  writeFileSync(
    join(APP, "src/data/backdrop.ts"),
    `// Generated by scripts/bake.mjs from art/backdrop.png. Do not edit.

// Source (1024x1536) pixels to panel pixels: x * SCALE + OFFSET_X.
export const SCALE = ${SCALE};
export const OFFSET_X = ${OFFSET_X};
export const OFFSET_Y = ${OFFSET_Y};

// The live window on the panel; art/base.png is the panel below it.
export const WINDOW_X = ${WINDOW.x};
export const WINDOW_Y = ${WINDOW.y};
export const WINDOW_W = ${WINDOW.width};
export const WINDOW_H = ${WINDOW.height};

// Yule's window: ${WINDOW.width}x${WINDOW.height} RGB565 words, little-endian, base64.
export const BACKDROP =
  "${base64}";
`,
  );
}

async function writeBase(words) {
  const baseTop = WINDOW.y + WINDOW.height;
  const rgbPanel = Buffer.from(toRgb(words));
  await sharp(rgbPanel.subarray(baseTop * WIDTH * 3), {
    raw: { width: WIDTH, height: HEIGHT - baseTop, channels: 3 },
  })
    .png({ compressionLevel: 9 })
    .toFile(join(APP, "public/art/base.png"));
}

// Saturated bright blobs, as panel-space centroids and colours: the largest
// `most` of the bulb-sized ones.
function findBulbs(pixels, width, area, most) {
  const blobs = findBlobs(pixels, width, area, (r, g, b) => {
    const max = Math.max(r, g, b);
    return max > 150 && max - Math.min(r, g, b) > 90;
  });
  return blobs
    .filter((blob) => blob.count >= 12 && blob.count <= 400)
    .sort((a, b) => b.count - a.count)
    .slice(0, Math.max(0, most))
    .flatMap((blob) => [Math.round(blob.x * SCALE + OFFSET_X), Math.round(blob.y * SCALE + OFFSET_Y), ...blob.colour]);
}

// 4-connected blobs of pixels passing `hot` inside `area` (source px): each
// one's centroid, pixel count and mean colour.
function findBlobs(pixels, width, area, hot) {
  const w = area.right - area.left;
  const h = area.bottom - area.top;
  const mask = new Uint8Array(w * h);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const at = ((area.top + y) * width + area.left + x) * 3;
      mask[y * w + x] = hot(pixels[at], pixels[at + 1], pixels[at + 2]) ? 1 : 0;
    }
  }

  const blobs = [];
  const stack = [];
  for (let start = 0; start < mask.length; start++) {
    if (!mask[start]) continue;

    let count = 0;
    let sx = 0;
    let sy = 0;
    const sum = [0, 0, 0];
    stack.push(start);
    mask[start] = 0;
    while (stack.length) {
      const at = stack.pop();
      const x = at % w;
      const y = (at / w) | 0;
      const p = ((area.top + y) * width + area.left + x) * 3;
      count++;
      sx += x;
      sy += y;
      sum[0] += pixels[p];
      sum[1] += pixels[p + 1];
      sum[2] += pixels[p + 2];
      for (const next of [at - 1, at + 1, at - w, at + w]) {
        if (next < 0 || next >= mask.length || !mask[next]) continue;
        if (Math.abs((next % w) - x) > 1) continue;

        mask[next] = 0;
        stack.push(next);
      }
    }
    blobs.push({
      x: area.left + sx / count,
      y: area.top + sy / count,
      count,
      colour: sum.map((v) => Math.round(v / count)),
    });
  }
  return blobs;
}

function toRgb(packed) {
  const out = new Uint8Array(packed.length * 3);
  for (let i = 0; i < packed.length; i++) {
    const v = packed[i];
    // Bit replication: converting back to RGB565 by truncation is exact.
    const r = v >> 11;
    const g = (v >> 5) & 63;
    const b = v & 31;
    out[i * 3] = (r << 3) | (r >> 2);
    out[i * 3 + 1] = (g << 2) | (g >> 4);
    out[i * 3 + 2] = (b << 3) | (b >> 2);
  }
  return out;
}
